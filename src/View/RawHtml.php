<?php

declare(strict_types=1);

namespace Zara\View;

/**
 * Represents raw HTML content.
 * 
 * Allows injecting HTML code directly into Zara templates without 
 * being filtered or sanitized by the infrastructure's anti-XSS protection.
 */
final class RawHtml
{
    /**
     * Initializes the object with its raw HTML string.
     *
     * @param string $content The unescaped HTML content.
     */
    public function __construct(
        private readonly string $content
    ) {}

    /**
     * Retrieves the original HTML content.
     * This method is invoked directly by the PHP code generated by RawParser.
     *
     * @return string
     */
    public function getContent(): string
    {
        return $this->content;
    }

    /**
     * Allows magic string casting of the object when manipulated outside RawParser.
     *
     * @return string
     */
    public function __toString(): string
    {
        return $this->content;
    }
}